static int in(const range_t *r, int n, uint32_t c)
{
    if (c < r[0].lo || c > r[n - 1].hi)
        return 0;
    int lo = 0, hi = n - 1;
    while (lo <= hi) {
        int m = (lo + hi) / 2;
        if (c < r[m].lo)
            hi = m - 1;
        else if (c > r[m].hi)
            lo = m + 1;
        else
            return 1;
    }
    return 0;
}

int utf8_width(uint32_t c)
{
    if (c >= 0x20 && c < 0x7f)
        return 1;
    if (c < 0x20 || (c >= 0x7f && c < 0xa0))
        return -1;
    /* bidirectional embeddings, overrides and isolates reorder the
     * terminal line; line / paragraph separators move the cursor */
    if ((c >= 0x202a && c <= 0x202e) || (c >= 0x2066 && c <= 0x2069) || c == 0x2028 || c == 0x2029 ||
        c == 0x200e || c == 0x200f || c == 0x061c)
        return -1;
    if (c == 0x00ad)
        return 1;
    if (in(ZERO, (int)(sizeof ZERO / sizeof ZERO[0]), c))
        return 0;
    if (in(WIDE, (int)(sizeof WIDE / sizeof WIDE[0]), c))
        return 2;
    return 1;
}
