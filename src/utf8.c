/* utf8.c - UTF-8 decoding and an approximate wcwidth().
 *
 * The width tables cover the common zero-width (combining) ranges and the
 * East Asian Wide / Fullwidth and emoji presentation ranges.  They are not
 * the full Unicode tables, but they keep columns aligned for CJK text and
 * emoji without depending on the locale of the remote machine. */
#include "utf8.h"

int utf8_decode(const unsigned char *s, size_t n, uint32_t *cp)
{
    unsigned c = s[0];
    if (c < 0x80) {
        *cp = c;
        return 1;
    }
    int len;
    uint32_t v, min;
    if (c >= 0xc2 && c <= 0xdf) {
        len = 2;
        v = c & 0x1f;
        min = 0x80;
    } else if (c >= 0xe0 && c <= 0xef) {
        len = 3;
        v = c & 0x0f;
        min = 0x800;
    } else if (c >= 0xf0 && c <= 0xf4) {
        len = 4;
        v = c & 0x07;
        min = 0x10000;
    } else {
        return 0;
    }
    if ((size_t)len > n)
        return 0;
    for (int i = 1; i < len; i++) {
        if ((s[i] & 0xc0) != 0x80)
            return 0;
        v = v << 6 | (s[i] & 0x3f);
    }
    if (v < min || v > 0x10ffff || (v >= 0xd800 && v <= 0xdfff))
        return 0;
    *cp = v;
    return len;
}

size_t utf8_encode(uint32_t cp, char *o)
{
    if (cp < 0x80) {
        o[0] = (char)cp;
        return 1;
    }
    if (cp < 0x800) {
        o[0] = (char)(0xc0 | cp >> 6);
        o[1] = (char)(0x80 | (cp & 0x3f));
        return 2;
    }
    if (cp < 0x10000) {
        o[0] = (char)(0xe0 | cp >> 12);
        o[1] = (char)(0x80 | (cp >> 6 & 0x3f));
        o[2] = (char)(0x80 | (cp & 0x3f));
        return 3;
    }
    o[0] = (char)(0xf0 | cp >> 18);
    o[1] = (char)(0x80 | (cp >> 12 & 0x3f));
    o[2] = (char)(0x80 | (cp >> 6 & 0x3f));
    o[3] = (char)(0x80 | (cp & 0x3f));
    return 4;
}

